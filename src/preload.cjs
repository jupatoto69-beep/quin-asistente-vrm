const { contextBridge, ipcRenderer } = require('electron');

contextBridge.exposeInMainWorld('assistant', {
  ready: () => ipcRenderer.invoke('assistant:ready'),
  companionStory: () => ipcRenderer.invoke('companion:story'),
  companionPresented: (id) => ipcRenderer.invoke('companion:presented', id),
  companionIdle: () => ipcRenderer.invoke('companion:idle'),
  fileFolders: () => ipcRenderer.invoke('files:folders'),
  addFileFolder: () => ipcRenderer.invoke('files:add-folder'),
  removeFileFolder: (path) => ipcRenderer.invoke('files:remove-folder', path),
  openLocalFile: (id) => ipcRenderer.invoke('files:open', id),
  chat: (text, body, avatarId, view, starter) => ipcRenderer.invoke('assistant:chat', { text, body, avatarId, view, starter }),
  gestureResult: (id, performed) => ipcRenderer.invoke('assistant:gesture-result', { id, performed }),
  visionPanel: (open) => ipcRenderer.invoke('vision:panel', open),
  visionSources: () => ipcRenderer.invoke('vision:sources'),
  authorizeVision: (source) => ipcRenderer.invoke('vision:authorize', source),
  captureScreen: (command) => ipcRenderer.invoke('vision:quick-capture', command),
  look: (question, image) => ipcRenderer.invoke('vision:look', { question, image }),
  onReplyChunk: (callback) => ipcRenderer.on('assistant:reply-chunk', (_event, chunk) => callback(chunk)),
  onWebSearch: (callback) => ipcRenderer.on('assistant:web-search', () => callback()),
  onTimer: (callback) => ipcRenderer.on('desktop:timer', (_event, text) => callback(text)),
  onReminder: (callback) => ipcRenderer.on('pending:due', (_event, due, count) => callback(due, count)),
  onPendingChanged: (callback) => ipcRenderer.on('pending:changed', () => callback()),
  listPending: () => ipcRenderer.invoke('pending:list'),
  completePending: (id) => ipcRenderer.invoke('pending:complete', id),
  openSource: (url) => ipcRenderer.invoke('assistant:open-source', url),
  speak: (text, tone) => ipcRenderer.invoke('assistant:speak', { text, tone }),
  speakStream: (text, tone) => ipcRenderer.invoke('assistant:speak-stream', { text, tone }),
  interrupt: (id) => ipcRenderer.invoke('assistant:interrupt', id),
  onVoiceChunk: (callback) => ipcRenderer.on('assistant:voice-chunk', (_event, chunk) => callback(chunk)),
  transcribe: (wav) => ipcRenderer.invoke('assistant:transcribe', wav),
  checkWake: (wav, waiting, interrupting) => ipcRenderer.invoke('assistant:wake-check', { wav, waiting, interrupting }),
  cancelWake: () => ipcRenderer.invoke('assistant:wake-cancel'),
  microphone: (requested) => ipcRenderer.invoke('assistant:microphone', requested),
  listMemory: (query, before, kind) => ipcRenderer.invoke('memory:list', { query, before, kind }),
  saveMemoryFact: (fact) => ipcRenderer.invoke('memory:save-fact', fact),
  removeMemoryFact: (id) => ipcRenderer.invoke('memory:remove-fact', id),
  onMemoryScope: (callback) => ipcRenderer.on('memory:scope', (_event, scope) => callback(scope)),
  onMemoryLearned: (callback) => ipcRenderer.on('memory:learned', () => callback()),
  removeNote: (id) => ipcRenderer.invoke('memory:remove-note', id),
  removeMemory: (id) => ipcRenderer.invoke('memory:remove', id),
  clearMemory: () => ipcRenderer.invoke('memory:clear'),
  getProfile: () => ipcRenderer.invoke('profile:get'),
  saveProfile: (text) => ipcRenderer.invoke('profile:save', text),
  getVoice: () => ipcRenderer.invoke('preferences:get-voice'),
  setVoice: (enabled) => ipcRenderer.invoke('preferences:set-voice', enabled),
  getWeb: () => ipcRenderer.invoke('preferences:get-web'),
  setWeb: (enabled) => ipcRenderer.invoke('preferences:set-web', enabled),
  getCompanion: () => ipcRenderer.invoke('preferences:get-companion'),
  setCompanion: (mode) => ipcRenderer.invoke('preferences:set-companion', mode),
  hasAvatar: () => ipcRenderer.invoke('preferences:has-avatar'),
  saveAvatar: (data) => ipcRenderer.invoke('preferences:save-avatar', data),
  resetAvatar: () => ipcRenderer.invoke('preferences:reset-avatar'),
  minimize: () => ipcRenderer.invoke('window:minimize'),
  close: () => ipcRenderer.invoke('window:close'),
  onCompanionVisibility: (callback) => ipcRenderer.on('window:companion-visible', (_event, visible) => callback(visible)),
  pointer: () => ipcRenderer.invoke('window:pointer'),
  passThrough: () => ipcRenderer.invoke('window:pass-through'),
  onPassThrough: (callback) => ipcRenderer.on('window:pass-through', (_event, enabled) => callback(enabled)),
});
